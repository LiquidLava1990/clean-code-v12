//! Shared test fixtures for the cc-score integration tests.
//!
//! Constructing a real [`cc_finding::Finding`] requires ~10 fields; we
//! centralise the boilerplate here so the actual test bodies stay
//! focused on the score algorithm.
#![allow(
    dead_code,
    missing_docs,
    clippy::missing_panics_doc,
    clippy::missing_const_for_fn
)]

use camino::Utf8PathBuf;
use cc_finding::{
    ActionableMessage, Category, CostClaim, Evidence, Finding, FindingBuilder, Location, Position,
    ProbeVersion, Remediation, Severity,
};

#[must_use]
pub fn sample_location() -> Location {
    Location {
        file: Utf8PathBuf::from("src/foo.rs"),
        start: Position::new(1, 1, 0),
        end: Position::new(2, 1, 10),
        node_id: None,
        function_qualified_name: None,
    }
}

#[must_use]
pub fn sample_message() -> ActionableMessage {
    ActionableMessage::new(
        "test finding",
        "synthetic finding generated by cc-score integration tests",
        Remediation::doc_link("https://cleancode.dev/test"),
    )
}

#[must_use]
pub fn sample_evidence() -> Evidence {
    Evidence {
        snippet: "fn x() {}".to_owned(),
        context_before: String::new(),
        context_after: String::new(),
        data_path: None,
        cpg_node_dump: None,
    }
}

#[must_use]
pub fn sample_probe_version() -> ProbeVersion {
    ProbeVersion::new("cc-score-test", "0.1.0", 1, None)
}

/// Build a finding with the requested severity + confidence and a
/// stable `Category::Shape` bucket.
#[must_use]
pub fn finding_with(sev: Severity, confidence: f32) -> Finding {
    finding_with_category(sev, confidence, Category::Shape)
}

/// Build a finding with the requested severity, confidence, and
/// explicit category.
#[must_use]
pub fn finding_with_category(sev: Severity, confidence: f32, cat: Category) -> Finding {
    FindingBuilder::new()
        .rule_id("cc.score.test")
        .category(cat)
        .location(sample_location())
        .message(sample_message())
        .evidence(sample_evidence())
        .severity(sev)
        .confidence(confidence)
        .cost(CostClaim::BlockingDebt { weight: 1 })
        .probe_version(sample_probe_version())
        .build()
        .expect("test finding builds")
}
